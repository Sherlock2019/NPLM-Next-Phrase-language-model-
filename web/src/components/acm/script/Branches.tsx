"use client";

/**
 * E · Next scenes. The authored branches come from the bundle (DemoProvider). If the API and
 * the local model are available, the model provider can add generated branches; they are
 * listed separately and labelled. No probabilities are shown. The selected branch plays in
 * the same 2D player and can be exported as scene directions.
 */

import { useEffect, useState } from "react";
import { nameOf, type Branch, type Directions, type SceneBundle, type Step } from "@/lib/acm/scene";
import { ScriptPlayer } from "./ScriptPlayer";
import { Dot, SourceBadge, StatusBadge, VALENCE, ValenceTag, btn } from "./shared";

type ModelState =
  | { kind: "checking" }
  | { kind: "off"; reason: string }
  | { kind: "ready"; reason: string }
  | { kind: "running" }
  | { kind: "error"; reason: string };

function download(name: string, data: unknown) {
  const url = URL.createObjectURL(new Blob([JSON.stringify(data, null, 1)], { type: "application/json" }));
  const a = document.createElement("a");
  a.href = url; a.download = name; a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function ExportButton({ directions, name }: { directions: Directions; name: string }) {
  return (
    <div className="flex flex-wrap items-center gap-2">
      <button type="button" className={btn} onClick={() => download(name, directions)}>⬇ Export scene directions (JSON)</button>
      <span className="faint text-[11.5px]">
        {directions.schema} · {directions.actions.length} actions · {directions.unsupported.length ? `${directions.unsupported.length} not representable by the player` : "all representable by the player"}.
        An export for future 3D / TTS adapters; no engine consumes it yet.
      </span>
    </div>
  );
}

export function Branches({ b, colors, focus }: { b: SceneBundle; colors: Record<string, string>; focus: string | null }) {
  const s = b.scene;
  const [generated, setGenerated] = useState<Branch[]>([]);
  const [model, setModel] = useState<ModelState>({ kind: "checking" });
  const [sel, setSel] = useState(b.branches[0]?.id);
  const all = [...b.branches, ...generated];
  const br = all.find((x) => x.id === sel) ?? all[0];
  const end = b.timeline[b.timeline.length - 1].state;

  useEffect(() => {
    fetch("/api/acm/scene/status")
      .then((r) => (r.ok ? r.json() : Promise.reject(new Error(`API ${r.status}`))))
      .then((d: { model: { available: boolean; reason: string } }) =>
        setModel(d.model.available ? { kind: "ready", reason: d.model.reason } : { kind: "off", reason: d.model.reason }))
      .catch((e: Error) => setModel({ kind: "off", reason: `the ACM API is not reachable (${e.message}); the demo works without it` }));
  }, []);

  const generate = async () => {
    setModel({ kind: "running" });
    try {
      const r = await fetch("/api/acm/scene/branches", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ scene: s.id }) });
      const d = await r.json().catch(() => ({}));
      if (!r.ok) throw new Error(d.detail ?? `${r.status} ${r.statusText}`);
      const list = (d.branches ?? []) as Branch[];
      if (!list.length) throw new Error("the model returned no valid branch");
      setGenerated(list);
      setSel(list[0].id);
      setModel({ kind: "ready", reason: `${list.length} generated by ${d.model ?? "the local model"}${d.rejected?.length ? ` · ${d.rejected.length} rejected by validation` : ""}` });
    } catch (e) {
      setModel({ kind: "error", reason: (e as Error).message });
    }
  };

  const steps: Step[] = br?.timeline ?? Array.from({ length: (br?.events.length ?? 0) + 1 }, (_, k) => ({ event: k ? br!.events[k - 1].id : null, state: end, changed: [] }));
  const Card = (x: Branch) => (
    <li key={x.id}>
      <button type="button" onClick={() => setSel(x.id)} aria-pressed={sel === x.id}
        className={`flex h-full w-full flex-col gap-1.5 rounded-xl border p-3 text-left transition-colors ${sel === x.id ? "border-cyan-400 bg-cyan-400/10" : "border-[var(--border)] hover:border-cyan-400/60"}`}>
        <span className="flex items-center justify-between gap-2">
          <span className="text-[10.5px] font-bold uppercase tracking-wider text-[var(--text-faint)]">Possible next scene {x.id}</span>
          <SourceBadge s={x.source} />
        </span>
        <span className="text-[15px] font-bold">{x.title}</span>
        <span className="dim text-[12px]">Assumes: {x.assumptions[0]}</span>
        <span className="flex flex-wrap gap-x-2.5 text-[11.5px]">
          {x.goal_changes.map((g) => (
            <span key={g.actor} className="inline-flex items-center gap-1" title={`${nameOf(s, g.actor)}: ${VALENCE[g.effect].label}`}>
              <Dot color={colors[g.actor] ?? "#94a3b8"} /><span style={{ color: colors[g.actor] }}>{nameOf(s, g.actor)}</span>
              <span className={VALENCE[g.effect].cls}>{VALENCE[g.effect].mark}<span className="sr-only"> {VALENCE[g.effect].label}</span></span>
            </span>
          ))}
        </span>
      </button>
    </li>
  );

  return (
    <div className="flex flex-col gap-4">
      <div className="flex flex-col items-center" role="group" aria-label="Possible next scenes">
        <div className="rounded-xl bg-[#0b1b2e] px-4 py-2.5 text-center text-[14px] font-semibold text-white ring-1 ring-white/10">
          Scene 1 ends: {s.status.toLowerCase()}
        </div>
        <div aria-hidden className="h-4 w-px bg-[var(--text-faint)]" />
        <ol className="grid w-full gap-2 sm:grid-cols-2 lg:grid-cols-4">{b.branches.map(Card)}</ol>
        <p className="faint mt-2 text-center text-[11.5px]">Possible continuations with stated assumptions, not predictions. No probabilities: nothing here could calibrate them.</p>
      </div>

      <div className="panel-raised flex flex-col gap-2 p-4">
        <div className="flex flex-wrap items-center gap-2">
          <p className="text-[13px] font-bold">Generate more with the local model</p>
          <SourceBadge s="generated_inference" />
          <button type="button" className={`${btn} ml-auto`} disabled={model.kind !== "ready"} onClick={generate}>
            {model.kind === "running" ? "Generating… (can take a minute)" : "Generate branches"}
          </button>
        </div>
        <p className={`text-[12px] ${model.kind === "error" ? "text-rose-500" : "faint"}`}>
          {model.kind === "checking" && "Checking whether the API and a local model are available…"}
          {model.kind === "off" && `Unavailable: ${model.reason}. The prewritten branches above are complete without it.`}
          {model.kind === "ready" && `Available: ${model.reason}. Output is validated against the scene; invalid items are dropped.`}
          {model.kind === "running" && "Asking the local model; its reply will be validated before it is shown."}
          {model.kind === "error" && `Generation failed: ${model.reason}. The prewritten branches are unaffected.`}
        </p>
        {generated.length > 0 && <ol className="grid gap-2 sm:grid-cols-2 lg:grid-cols-4">{generated.map(Card)}</ol>}
      </div>

      {br && (
        <article className="flex flex-col gap-4 rounded-xl border border-[var(--border)] p-4 sm:p-5" aria-live="polite">
          <header className="flex flex-wrap items-center gap-2">
            <span className="rounded bg-cyan-400/15 px-2 py-0.5 text-[11px] font-bold uppercase text-cyan-500">Possible next scene {br.id}</span>
            <h3 className="text-[19px] font-bold">{br.title}</h3>
            <SourceBadge s={br.source} />
          </header>
          <p className="text-[14.5px]">{br.summary}</p>
          <ScriptPlayer key={br.id} scene={s} events={br.events} steps={steps} colors={colors} focus={focus} label={`Branch ${br.id}`} />

          <div className="grid gap-4 md:grid-cols-2">
            <section>
              <p className="faint mb-1 text-[11px] font-bold uppercase">Assumptions</p>
              <ul className="list-disc pl-5 text-[13.5px]">{br.assumptions.map((x) => <li key={x}>{x}</li>)}</ul>
              <p className="faint mb-1 mt-3 text-[11px] font-bold uppercase">Why it is plausible</p>
              <p className="text-[13.5px]">{br.plausibility}</p>
            </section>
            <section>
              <p className="faint mb-1 text-[11px] font-bold uppercase">How each goal may be affected</p>
              <ul className="flex flex-col gap-1.5">
                {br.goal_changes.map((g) => (
                  <li key={g.actor} className={`border-l-4 pl-3 text-[13.5px] ${focus && focus !== g.actor ? "opacity-40" : ""}`} style={{ borderColor: colors[g.actor] }}>
                    <b style={{ color: colors[g.actor] }}>{nameOf(s, g.actor)}:</b> {g.change} <ValenceTag v={g.effect} />
                  </li>
                ))}
              </ul>
            </section>
            <section>
              <p className="faint mb-1 flex items-center gap-2 text-[11px] font-bold uppercase">Possible behaviour and feelings <StatusBadge s="possible" /></p>
              <ul className="flex flex-col gap-1 text-[13.5px] italic">
                {Object.entries(br.inferences).flatMap(([id, list]) => list.map((x) => (
                  <li key={id + x.text} className={focus && focus !== id ? "opacity-40" : ""}><b className="not-italic" style={{ color: colors[id] }}>{nameOf(s, id)}:</b> {x.text}</li>
                )))}
              </ul>
            </section>
            <section>
              <p className="faint mb-1 flex items-center gap-2 text-[11px] font-bold uppercase">Still unknown <StatusBadge s="unknown" /></p>
              <ul className="list-disc pl-5 text-[13.5px]">{br.unknowns.map((x) => <li key={x}>{x}</li>)}</ul>
              {br.consequences.length > 0 && (
                <>
                  <p className="faint mb-1 mt-3 text-[11px] font-bold uppercase">Possible consequences</p>
                  <ul className="flex flex-col gap-1 text-[13.5px]">
                    {br.consequences.map((c) => <li key={c.id} className="flex flex-wrap items-center gap-2">{c.description} <StatusBadge s={c.status} /></li>)}
                  </ul>
                </>
              )}
            </section>
          </div>
          {br.directions
            ? <ExportButton directions={br.directions} name={`${s.id}_branch_${br.id}_directions.json`} />
            : <button type="button" className={`${btn} self-start`} onClick={() => download(`${s.id}_generated_${br.id}.json`, br)}>⬇ Export this generated branch (JSON)</button>}
        </article>
      )}
    </div>
  );
}
