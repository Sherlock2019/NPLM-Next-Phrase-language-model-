/** Badges for provenance, status, effect and time horizon, used across the ACM scene demo. */

import type { Horizon, Source, Status, Valence } from "@/lib/acm/scene";

export const STATUS: Record<Status, { label: string; cls: string; hint: string }> = {
  stated: { label: "Stated", cls: "bg-emerald-400/15 text-emerald-500 ring-emerald-400/40", hint: "Stated by the script or the scenario facts" },
  possible: { label: "Possible inference", cls: "bg-sky-400/15 text-sky-500 ring-sky-400/40", hint: "Plausible, not observed" },
  unknown: { label: "Unknown", cls: "bg-slate-400/15 text-[var(--text-dim)] ring-slate-400/40", hint: "Not established by the scene" },
  not_identified: { label: "Not identified", cls: "bg-transparent text-[var(--text-faint)] ring-[var(--border)]", hint: "No specific effect identified for this scope" },
};

export const SOURCE: Record<Source, { label: string; cls: string; hint: string }> = {
  scenario_fact: { label: "Scenario fact", cls: "bg-emerald-400/10 text-emerald-500 ring-emerald-400/40", hint: "Given by the scenario" },
  authored_demo: { label: "Authored demo content", cls: "bg-amber-400/15 text-amber-500 ring-amber-400/40", hint: "Written for this demo; not a model prediction" },
  generated_inference: { label: "Model-generated", cls: "bg-fuchsia-400/15 text-fuchsia-500 ring-fuchsia-400/40", hint: "Generated by the local language model and validated; not verified" },
  unknown: { label: "Unknown source", cls: "bg-slate-400/15 text-[var(--text-dim)] ring-slate-400/40", hint: "Provenance not recorded" },
};

export const VALENCE: Record<Valence, { label: string; mark: string; cls: string }> = {
  positive: { label: "positive", mark: "▲", cls: "text-emerald-500" },
  negative: { label: "negative", mark: "▼", cls: "text-rose-500" },
  mixed: { label: "mixed", mark: "◆", cls: "text-amber-500" },
  undetermined: { label: "undetermined", mark: "?", cls: "text-[var(--text-dim)]" },
};

export const HORIZON: Record<Horizon, string> = { immediate: "Immediate", later: "Later (possible reaction)", unknown: "Timing unknown" };

const pill = "inline-flex shrink-0 items-center rounded px-1.5 py-0.5 text-[10.5px] font-bold uppercase tracking-wide ring-1";

export function StatusBadge({ s }: { s: Status }) {
  return <span title={STATUS[s].hint} className={`${pill} ${STATUS[s].cls}`}>{STATUS[s].label}</span>;
}

export function SourceBadge({ s }: { s: Source }) {
  return <span title={SOURCE[s].hint} className={`${pill} ${SOURCE[s].cls}`}>{SOURCE[s].label}</span>;
}

export function ValenceTag({ v, who }: { v: Valence; who?: string }) {
  const t = VALENCE[v];
  return (
    <span className={`inline-flex items-center gap-1 text-[11.5px] font-semibold ${t.cls}`}>
      <span aria-hidden>{t.mark}</span>{who ? `${t.label} for ${who}` : t.label}
    </span>
  );
}

export function Dot({ color, square = false }: { color: string; square?: boolean }) {
  return <span aria-hidden className={`inline-block size-2.5 shrink-0 ${square ? "rounded-sm" : "rounded-full"}`} style={{ background: color }} />;
}

export const btn = "rounded-lg border border-[var(--border)] px-3 py-1.5 text-[13px] font-semibold hover:border-cyan-400 disabled:opacity-40 disabled:hover:border-[var(--border)]";
